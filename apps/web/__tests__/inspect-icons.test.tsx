import { describe, expect, it } from 'vitest'
import { render } from '@testing-library/react'
import { inspectEnumIcon, inspectOptionLabel, inspectPropIcon, paletteTypeIcon } from '../lib/inspect/icons'

describe('inspect icons', () => {
  it('maps layout props and palette types to glyphs', () => {
    expect(inspectPropIcon('width')).toBeTruthy()
    expect(inspectPropIcon('direction')).toBeTruthy()
    expect(inspectPropIcon('textDecoration')).toBeTruthy()
    expect(inspectPropIcon('variant')).toBeTruthy()
    expect(inspectPropIcon('unknownProp')).toBeNull()
    expect(paletteTypeIcon('Stack')).toBeTruthy()
    expect(paletteTypeIcon('Button')).toBeTruthy()
    expect(paletteTypeIcon('Chip')).toBeTruthy()
    expect(paletteTypeIcon('Panel')).toBeTruthy()
    expect(paletteTypeIcon('Lede')).toBeTruthy()
    expect(paletteTypeIcon('FilterRow')).toBeTruthy()
    expect(paletteTypeIcon('RankedList')).toBeTruthy()
    expect(paletteTypeIcon('SectionChrome')).toBeTruthy()
  })

  it('maps enum values used by segmented inspect rows', () => {
    expect(inspectEnumIcon('direction', 'column')).toBeTruthy()
    expect(inspectEnumIcon('align', 'center')).toBeTruthy()
    expect(inspectEnumIcon('justify', 'space-between')).toBeTruthy()
    expect(inspectEnumIcon('textAlign', 'start')).toBeTruthy()
    expect(inspectEnumIcon('wrap', 'true')).toBeTruthy()
    expect(inspectEnumIcon('textDecoration', 'underline')).toBeTruthy()
    expect(inspectEnumIcon('textTransform', 'uppercase')).toBeTruthy()
    expect(inspectEnumIcon('borderStyle', 'dashed')).toBeTruthy()
    expect(inspectEnumIcon('density', 'compact')).toBeTruthy()
    expect(inspectEnumIcon('density', 'default')).toBeTruthy()
    expect(inspectEnumIcon('density', 'comfortable')).toBeTruthy()
    expect(inspectEnumIcon('borders', 'none')).toBeTruthy()
    expect(inspectEnumIcon('borders', 'row')).toBeTruthy()
    expect(inspectEnumIcon('borders', 'all')).toBeTruthy()
    expect(inspectEnumIcon('variant', 'primary')).toBeTruthy()
    expect(inspectPropIcon('openAssetLibrary')).toBeTruthy()
    expect(inspectPropIcon('openSvgDeepEdit')).toBeTruthy()
    expect(inspectPropIcon('table_add_row')).toBeTruthy()
    expect(inspectEnumIcon('size', 'sm')).toBeTruthy()
    expect(inspectEnumIcon('tone', 'danger')).toBeTruthy()
    expect(inspectEnumIcon('tone', 'info')).toBeTruthy()
    expect(inspectEnumIcon('tone', 'muted')).toBeTruthy()
    expect(inspectEnumIcon('tone', 'solid')).toBeTruthy()
    expect(inspectEnumIcon('tone', 'accent')).toBeTruthy()
    expect(inspectEnumIcon('tone', 'default')).toBeTruthy()
    expect(inspectEnumIcon('orientation', 'vertical')).toBeTruthy()
    expect(inspectEnumIcon('orientation', 'both')).toBeTruthy()
    expect(inspectEnumIcon('variant', 'magazine')).toBeTruthy()
    expect(inspectEnumIcon('shape', 'round')).toBeTruthy()
    expect(inspectEnumIcon('level', 'ok')).toBeTruthy()
    expect(inspectEnumIcon('axis', 'y')).toBeTruthy()
    expect(inspectEnumIcon('disabled', 'true')).toBeTruthy()
    expect(inspectEnumIcon('columns', '2')).toBeTruthy()
  })

  it('uses distinct glyphs for font family / size / weight', () => {
    const { container: family } = render(<>{inspectPropIcon('fontFamily')}</>)
    const { container: size } = render(<>{inspectPropIcon('fontSize')}</>)
    const { container: weight } = render(<>{inspectPropIcon('fontWeight')}</>)
    const d = (root: HTMLElement) =>
      Array.from(root.querySelectorAll('path'))
        .map((p) => p.getAttribute('d') ?? '')
        .join('|')
    expect(d(family)).toBeTruthy()
    expect(d(size)).toBeTruthy()
    expect(d(weight)).toBeTruthy()
    expect(d(family)).not.toBe(d(size))
    expect(d(size)).not.toBe(d(weight))
    expect(d(family)).not.toBe(d(weight))
    expect(family.querySelectorAll('path').length).toBeLessThan(weight.querySelectorAll('path').length)
  })

  it('uses contract values as labels for unicode direction arrows', () => {
    expect(inspectOptionLabel('column', '↓')).toBe('column')
    expect(inspectOptionLabel('center', 'center')).toBe('center')
  })
})
