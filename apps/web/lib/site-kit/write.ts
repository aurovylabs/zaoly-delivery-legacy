export function resolveSiteKitRoot(cwd = process.cwd()): string {
  const env = process.env[paths.envSiteKitRoot]?.trim()
  if (env) return path.resolve(env)
  // Next cwd is usually apps/web → go up to repo root
  const fromWeb = path.resolve(cwd, '../..', paths.siteKitPackageRelPath)
  const fromRoot = path.resolve(cwd, paths.siteKitPackageRelPath)
  return fromWeb
}

export function patchStoryArgs(source: string, args: Record<string, unknown>): string {
  const next = formatCsfArgsObject(args)
  const replaced = source.replace(/args:\s*\{[\s\S]*?\n  \}/m, `args: ${next}`)
  if (replaced === source) {
    return source.replace(
      /(tags:\s*\[[^\]]*\]\s*,)/m,
      `$1\n  args: ${next},`,
    )
  }
  return replaced
}

export function patchTokenBindings(
  source: string,
  tokenBindings: Record<string, string>,
): string {
  const body = Object.entries(tokenBindings)
    .map(([k, v]) => `      ${k}: ${JSON.stringify(v)},`)
    .join('\n')
  const block = `parameters: {\n    tokenBindings: {\n${body}\n    },\n  },`
  if (/parameters:\s*\{[\s\S]*?tokenBindings:/.test(source)) {
    return source.replace(
      /parameters:\s*\{[\s\S]*?\n  \},/m,
      `${block}`,
    )
  }
  return source.replace(/(tags:\s*\[[^\]]*\]\s*,)/m, `$1\n  ${block}`)
}

/** Drop seed demo CSF exports that compete with Master named variants. */
export function stripSeedDemoStories(source: string): string {
  return source.replace(
    /\nexport const (Secondary|Ghost|Primary):\s*(?:Story|StoryObj<[^>]*>)\s*=\s*\{[\s\S]*?\n\}\n?/g,
    '\n',
  )
}

export type AtomNamedVariant = KitNamedVariantCell & {
  composition: Record<string, unknown>
}

export function atomStoryExportName(raw: string): string {
  const trimmed = raw.trim()
  if (!trimmed) return 'Variant'
  if (/^[A-Z][A-Za-z0-9]*$/.test(trimmed)) return trimmed.slice(0, 48)
  const parts = trimmed.split(/[^A-Za-z0-9]+/).filter(Boolean)
  if (!parts.length) return 'Variant'
  const named = parts
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
    .slice(0, 48)
  return /^[A-Za-z]/.test(named) ? named : `V${named}`
}

/** Full CSF regenerate: Default-only, named variants, or Component Set axes. */
export function generateAtomStorySource(
  entry: { exportName: string; title: string },
  options: {
    args?: Record<string, unknown>
    tokenBindings?: Record<string, string>
    variants?: AtomNamedVariant[]
    axes?: KitMasterAxis[]
    defaultVariantId?: string
  },
): string {
  return generateAtomNamedVariantCsf({
    exportName: entry.exportName,
    title: entry.title,
    args: options.args,
    tokenBindings: options.tokenBindings,
    variants: options.variants ?? [],
    axes: options.axes,
    defaultVariantId: options.defaultVariantId,
    headerComment: options.axes?.length
      ? '/** Generated by CREATION Write — Master Component Set (axis controls). */'
      : options.variants && options.variants.length >= 2
        ? '/** Generated by CREATION Write — Master named variants as CSF + Controls.variant select. */'
        : undefined,
  })
}

export type SiteKitWriteInput = {
  componentId: string
  args?: Record<string, unknown>
  tokenBindings?: Record<string, string>
  /** Nested editor tree with resolved CSS (alignment, token colors, …). */
  composition?: Record<string, unknown>
  variants?: AtomNamedVariant[]
  defaultVariantId?: string
  /** Phase 3 Component Set axes — persisted on override + CSF controls. */
  axes?: KitMasterAxis[]
  /** SK-S4: `seed` = global Site* (shared lane); `fork` = Collection Atom~ id. */
  publishLane?: 'seed' | 'fork'
  /** Required for fork lane. */
  platformProjectId?: string | null
}

export type SiteKitWriteResult =
  | {
      ok: true
      wrote: string[]
      writesGit: false
      variantCount?: number
      axisCount?: number
      componentId?: string
      publishLane?: 'seed' | 'fork'
      platformProjectId?: string | null
    }
  | { ok: false; code: string; error: string }

export async function writeSiteKitStory(
  input: SiteKitWriteInput,
  options?: { kitRoot?: string; cwd?: string },
): Promise<SiteKitWriteResult> {
  const target = resolveAtomWriteTarget({
    componentId: input.componentId,
    publishLane: input.publishLane,
    platformProjectId: input.platformProjectId,
  })
  if (!target.ok) {
    return { ok: false, code: target.code, error: target.error }
  }

  const entry = findSiteKitEntry(target.baseComponentId)
  if (!entry) {
    return {
      ok: false,
      code: 'unknown-component',
      error: `Unknown componentId: ${target.baseComponentId}`,
    }
  }

  const kitRoot = options?.kitRoot ?? resolveSiteKitRoot(options?.cwd)
  const storyAbs = path.resolve(kitRoot, entry.storyFile)
  const rel = path.relative(kitRoot, storyAbs)
  if (rel.startsWith('..') || path.isAbsolute(rel)) {
    return { ok: false, code: 'path-escape', error: 'Story path escapes kit root' }
  }

  const wrote: string[] = []
  const cwd = options?.cwd ?? process.cwd()
  const validated = validateKitComponentSetPayload(
    input.variants && input.variants.length >= 2 ? input.variants : undefined,
    input.axes,
  )
  if (!validated.ok) {
    return { ok: false, code: validated.code, error: validated.error }
  }
  const namedVariants =
    validated.variants.length >= 2
      ? (validated.variants as AtomNamedVariant[])
      : undefined
  const axes = namedVariants && validated.axes?.length ? validated.axes : undefined
  const defaultVariantId =
    namedVariants &&
    (namedVariants.find((v) => v.id === input.defaultVariantId)?.id ?? namedVariants[0]?.id)
  const primaryComposition =
    namedVariants && defaultVariantId
      ? (namedVariants.find((v) => v.id === defaultVariantId)?.composition ??
        input.composition)
      : input.composition

  // Seed lane only — never patch global CSF for Collection forks.
  if (target.patchDiskStory) {
    try {
      const source = generateAtomStorySource(entry, {
        args: input.args,
        tokenBindings: input.tokenBindings,
        variants: namedVariants,
        axes,
        defaultVariantId: defaultVariantId ?? undefined,
      })
      await writeFile(storyAbs, source, 'utf8')
      wrote.push(entry.storyFile)
    } catch {
      // ignore — override still syncs Storybook
    }
  }

  const override = await writeSiteKitOverride(
    {
      componentId: target.overrideId,
      args: input.args ?? {},
      tokenBindings: input.tokenBindings ?? {},
      ...(primaryComposition ? { composition: primaryComposition } : {}),
      ...(namedVariants
        ? {
            variants: namedVariants.map((v) => ({
              id: v.id,
              name: v.name,
              composition: v.composition,
              ...(v.combination ? { combination: { ...v.combination } } : {}),
            })),
            defaultVariantId,
          }
        : {}),
      ...(axes ? { axes } : {}),
      ...(target.lane === 'fork' && target.platformProjectId
        ? { platformProjectId: target.platformProjectId }
        : {}),
      updatedAt: new Date().toISOString(),
    },
    { cwd },
  )
  if (!override.ok) return override
  wrote.push(...override.wrote)

  return {
    ok: true,
    wrote,
    writesGit: false,
    componentId: target.overrideId,
    publishLane: target.lane,
    platformProjectId: target.platformProjectId,
    ...(namedVariants ? { variantCount: namedVariants.length } : {}),
    ...(axes ? { axisCount: axes.length } : {}),
  }
}
