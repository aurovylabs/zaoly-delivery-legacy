export function isSafeTypeIdent(type: string): boolean {
  return /^[A-Za-z][A-Za-z0-9]*$/.test(type)
}

export function promotedStoryPathForType(type: string): string {
  if (!isSafeTypeIdent(type)) {
    throw new Error(`Unsafe type ident: ${type}`)
  }
  if (type.startsWith('Print')) return `packages/ui/src/print/${type}.promoted.stories.tsx`
  return `packages/ui/src/components/${type}.promoted.stories.tsx`
}

export const PROMOTED_TEMPLATE_STORY_PATH =
  'packages/ui/src/print/PrintPromotedTemplate.stories.tsx'

function jsLiteral(value: unknown): string {
  return JSON.stringify(value, null, 2)
}

export function renderPromotedArgsStory(input: {
  type: string
  args: Record<string, unknown>
  zaolyUiSource: string
}): string {
  const type = input.type
  if (!isSafeTypeIdent(type)) {
    throw new Error(`Unsafe type ident: ${type}`)
  }
  const print = type.startsWith('Print')
  const { tokenBindings, ...args } = input.args
  const parameters: Record<string, unknown> = { zaolyUiSource: input.zaolyUiSource }
  if (tokenBindings !== undefined) parameters.tokenBindings = tokenBindings
  const imports = print
    ? `import { createElement } from 'react'\nimport { PrintPage, ${type} } from './PrintPrimitives'`
    : `import { ${type} } from './${type}'`
  const renderLine = print
    ? `  render: (storyArgs) => createElement(PrintPage, null, createElement(${type}, storyArgs)),\n`
    : ''
  return `import type { Meta, StoryObj } from '@storybook/react-vite'
${imports}

const meta = {
  title: '${print ? `Print/${type.replace(/^Print/, '')}/Promoted` : `Promoted/${type}`}',
  component: ${type},
  tags: ['promoted'],
  parameters: ${jsLiteral(parameters)},
} satisfies Meta<typeof ${type}>

export default meta
type Story = StoryObj<typeof meta>

/** Generated by CREATION library promote (P1). Do not edit human Default stories. */
export const Promoted: Story = {
  args: ${jsLiteral(args)},
${renderLine}}
`
}

export function renderPromotedTemplateStory(input: {
  sanitizedScene: unknown
  zaolyUiSource: string
}): string {
  return `import type { Meta, StoryObj } from '@storybook/react-vite'
import { createElement } from 'react'
import { PrintPage } from './PrintPrimitives'

const meta = {
  title: 'Print/PromotedTemplate',
  component: PrintPage,
  tags: ['print', 'promoted', 'template'],
  parameters: {
    zaolyUiSource: ${jsLiteral(input.zaolyUiSource)},
    sanitizedScene: ${jsLiteral(input.sanitizedScene)},
  },
} satisfies Meta<typeof PrintPage>

export default meta
type Story = StoryObj<typeof meta>

/** Sanitized composition fixture. Generated by CREATION promote P2. */
export const Fixture: Story = {
  args: { folioTitle: 'Promoted template' },
  render: (storyArgs) =>
    createElement(
      PrintPage,
      storyArgs,
      createElement('p', null, 'See story parameters.sanitizedScene — Collection ids and live payloads stripped.'),
    ),
}
`
}

export function isAllowedPromoteGitPath(filePath: string): boolean {
  if (!filePath.startsWith('packages/ui/src/')) return false
  if (filePath.includes('..') || filePath.includes('\\')) return false
  if (filePath === PROMOTED_TEMPLATE_STORY_PATH) return true
  if (filePath.endsWith('.promoted.stories.tsx')) return true
  if (/^packages\/ui\/src\/components\/[A-Za-z][A-Za-z0-9]*\.promoted\.extend\.test\.tsx$/.test(filePath)) {
    return true
  }
  if (/^packages\/ui\/src\/components\/[A-Za-z][A-Za-z0-9]*\.tsx$/.test(filePath)) {
    return true
  }
  return false
}
