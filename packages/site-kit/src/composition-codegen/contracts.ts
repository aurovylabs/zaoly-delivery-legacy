export const DENIED_PROP_KEYS = new Set([
  'dangerouslySetInnerHTML',
  'dangerouslySetInnerText',
  'slot',
  'key',
  'ref',
  'suppressContentEditableWarning',
  'suppressHydrationWarning',
])

/** Contract props allowed in serialized composition `props` (paint lives in `style`). */
export const SITE_KIT_ALLOWED_PROPS: Record<string, ReadonlySet<string>> = {
  SiteButton: new Set(['children', 'variant', 'name', 'type', 'disabled']),
  SiteText: new Set(['children', 'role', 'name']),
  SiteLink: new Set(['children', 'href', 'name', 'target', 'rel']),
  SiteInput: new Set(['placeholder', 'name', 'type', 'value', 'defaultValue', 'disabled']),
  SiteTextarea: new Set(['placeholder', 'name', 'rows', 'value', 'defaultValue', 'disabled']),
  SiteSelect: new Set(['children', 'name', 'options', 'value', 'defaultValue', 'disabled']),
  SiteCheckbox: new Set(['children', 'name', 'checked', 'defaultChecked', 'disabled']),
  SiteBadge: new Set(['children', 'variant', 'name']),
  SiteChart: new Set(['chartType', 'variant', 'data', 'chartStyle', 'title', 'height', 'name']),
  SiteGauge: new Set(['value', 'min', 'max', 'label', 'unit', 'tone', 'name']),
  SiteImage: new Set(['src', 'alt', 'name']),
  /** `mark` is scene/inspect-only — snapshot expands into markup; do not paint to DOM. */
  SiteSvg: new Set(['markup', 'viewBox', 'alt', 'title', 'name']),
  SiteContainer: new Set(['children', 'name']),
  SiteStack: new Set(['children', 'name']),
  SiteGrid: new Set(['children', 'name']),
  SiteDivider: new Set(['name']),
  SiteTable: new Set(['children', 'name', 'density', 'borders', 'striped', 'caption']),
  SiteTableRow: new Set(['children', 'name', 'header']),
  SiteTableCell: new Set(['children', 'name', 'header', 'align']),
}

export function isAllowedSiteKitProp(type: string, key: string): boolean {
  if (DENIED_PROP_KEYS.has(key) || SITE_KIT_PAINT_PROP_KEYS.has(key) || key === 'slot') {
    return false
  }
  const allowed = SITE_KIT_ALLOWED_PROPS[type]
  if (!allowed) return false
  return allowed.has(key)
}
