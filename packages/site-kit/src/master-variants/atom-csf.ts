/**
 * Atom CSF for Master named variants / Component Sets.
 * Spec: site-kit-write.md · composition-masters.md Phase 3
 */
import { storyExportName } from '../composition-codegen/identifiers'
import { defaultAxisPicks } from './resolve'
import type { KitMasterAxis, KitNamedVariantCell } from './types'
import {
  csfStringLiteral,
  sanitizeCsfBlockComment,
  sanitizeKitAxes,
} from './validate-wire'

function formatArgKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key)
}

export function formatCsfArgsObject(args: Record<string, unknown>): string {
  const lines = Object.entries(args).map(([k, v]) => {
    const key = formatArgKey(k)
    if (typeof v === 'string') return `    ${key}: ${JSON.stringify(v)},`
    if (typeof v === 'number' || typeof v === 'boolean') return `    ${key}: ${String(v)},`
    return `    ${key}: ${JSON.stringify(v)},`
  })
  return `{\n${lines.join('\n')}\n  }`
}

function formatAxisArgTypes(axes: KitMasterAxis[]): string {
  return axes
    .map(
      (axis) => `    ${formatArgKey(axis.id)}: {
      name: ${JSON.stringify(axis.name)},
      description: 'Master Component Set axis',
      control: { type: 'select' },
      options: ${JSON.stringify(axis.values)},
    },`,
    )
    .join('\n')
}

export type GenerateAtomNamedVariantCsfOptions = {
  exportName: string
  title: string
  args?: Record<string, unknown>
  tokenBindings?: Record<string, string>
  variants: KitNamedVariantCell[]
  axes?: KitMasterAxis[]
  defaultVariantId?: string
  /** Doc comment under imports. */
  headerComment?: string
}

/** Full CSF: Default-only, flat named variants, or Component Set axis controls. */
export function generateAtomNamedVariantCsf(
  options: GenerateAtomNamedVariantCsfOptions,
): string {
  const rawArgs = { ...(options.args ?? {}) }
  delete rawArgs.variant
  delete rawArgs.masterVariant
  delete rawArgs.variantName
  const args = rawArgs
  const tokenBlock =
    options.tokenBindings && Object.keys(options.tokenBindings).length > 0
      ? `  parameters: {\n    tokenBindings: {\n${Object.entries(options.tokenBindings)
          .map(([k, v]) => `      ${k}: ${JSON.stringify(v)},`)
          .join('\n')}\n    },\n  },\n`
      : ''

  const titleLit = csfStringLiteral(options.title)
  const named = options.variants.length >= 2 ? options.variants : undefined
  const defaultHeader =
    '/** Generated by CREATION Write — Master named variants / Component Sets. */'
  const header = sanitizeCsfBlockComment(
    options.headerComment ?? defaultHeader,
    defaultHeader,
  )

  if (!named) {
    return `import type { Meta, StoryObj } from '@storybook/react-vite'
import { ${options.exportName} } from './${options.exportName}'

/** Generated by CREATION Write — Default only (no seed demo CSF exports). */
const meta = {
  title: ${titleLit},
  component: ${options.exportName},
  tags: ['site-kit'],
${tokenBlock}  args: ${formatCsfArgsObject(args)},
  argTypes: {
    variant: { control: false, table: { disable: true } },
  },
} satisfies Meta<typeof ${options.exportName}>

export default meta
type Story = StoryObj<typeof meta>

export const Default: Story = {}
`
  }

  const axes = sanitizeKitAxes(options.axes)
  const ordered = [...named]
  if (options.defaultVariantId) {
    const idx = ordered.findIndex((v) => v.id === options.defaultVariantId)
    if (idx > 0) {
      const [def] = ordered.splice(idx, 1)
      ordered.unshift(def!)
    }
  }
  const rows = ordered
    .map((v) => ({
      storyName: storyExportName(v.name),
      variantName: v.name,
      combination: v.combination,
    }))
    .filter((row, index, all) => all.findIndex((x) => x.storyName === row.storyName) === index)

  if (axes) {
    const defaultCell =
      ordered.find((v) => v.id === options.defaultVariantId) ?? ordered[0]
    const axisDefaults = defaultAxisPicks(axes, defaultCell)
    const metaArgs = formatCsfArgsObject({ ...args, ...axisDefaults })
    const axisArgTypes = formatAxisArgTypes(axes)
    const stories = rows
      .map((row) => {
        const storyArgs = defaultAxisPicks(axes, {
          id: '',
          name: row.variantName,
          combination: row.combination,
        })
        return `export const ${row.storyName}: Story = {
  args: ${formatCsfArgsObject(storyArgs)},
}`
      })
      .join('\n\n')

    return `import type { Meta, StoryObj } from '@storybook/react-vite'
import { ${options.exportName} } from './${options.exportName}'

${header}
const meta = {
  title: ${titleLit},
  component: ${options.exportName},
  tags: ['site-kit', 'named-variants', 'component-set'],
${tokenBlock}  args: ${metaArgs},
  argTypes: {
${axisArgTypes}
    variant: { control: false, table: { disable: true } },
  },
} satisfies Meta<typeof ${options.exportName}>

export default meta
type Story = StoryObj<typeof meta>

${stories}
`
  }

  const optionNames = JSON.stringify(rows.map((r) => r.variantName))
  const defaultVariant = rows[0]!.variantName
  const argsWithVariant = formatCsfArgsObject({
    ...args,
    variant: defaultVariant,
  })
  const stories = rows
    .map(
      (row) => `export const ${row.storyName}: Story = {
  args: { variant: ${JSON.stringify(row.variantName)} },
}`,
    )
    .join('\n\n')

  return `import type { Meta, StoryObj } from '@storybook/react-vite'
import { ${options.exportName} } from './${options.exportName}'

${header}
const meta = {
  title: ${titleLit},
  component: ${options.exportName},
  tags: ['site-kit', 'named-variants'],
${tokenBlock}  args: ${argsWithVariant},
  argTypes: {
    variant: {
      name: 'variant',
      description: 'Master named variant',
      control: { type: 'select' },
      options: ${optionNames},
    },
  },
} satisfies Meta<typeof ${options.exportName}>

export default meta
type Story = StoryObj<typeof meta>

${stories}
`
}
